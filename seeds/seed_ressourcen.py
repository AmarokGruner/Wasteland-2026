    conn = get_connection()
    c = conn.cursor()
    ins = upd = 0
    print(f"\n🔹 Ressourcen:")
    for row in RESSOURCEN_DATA:
        if save_entity(c, "ressourcen", row):
            print(f"  ✅  ID {row['id']:>3} | {row['name']} – neu")
            ins += 1
        else:
            upd += 1
    conn.commit()
    conn.close()
    print(f"   → {ins} neu, {upd} aktualisiert")
    return ins, upd

