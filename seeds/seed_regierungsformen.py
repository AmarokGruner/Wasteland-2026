def seed():
    conn = get_connection()
    c = conn.cursor()
    ins = upd = 0
    print("\n🔹 Regierungsformen:")
    for r in REGIERUNGSFORMEN_DATA:
        if save_entity(c, "regierungsformen", r, id_field="id"):
            print(f"  ✅  Regierungsform: {r['name']} (ID={r['id']}) – neu")
            ins += 1
        else:
            print(f"  🔄  Regierungsform: {r['name']} (ID={r['id']}) – aktualisiert")
            upd += 1
    conn.commit()
    conn.close()
    return ins, upd

if __name__ == "__main__":
    seed()
